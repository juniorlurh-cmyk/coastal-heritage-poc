import { useMemo, useState } from 'react';
import { Link } from 'react-router-dom';
import FadeIn from '../components/FadeIn';
import SectionHeading from '../components/SectionHeading';
import { Icon } from '../components/Icons';
import { MARKET_DATA, SERVICES, topAreas } from '../data/market';
import { AREAS } from '../data/areas';
import { analyseMarket, AI_ENABLED, AI_MODEL } from '../ai/provider';
import VizBoard from '../components/VizBoard';

const areaImage = Object.fromEntries(AREAS.map((a) => [a.id, a.image]));

function demandClass(score) {
  if (score >= 75) return 'hot';
  if (score >= 60) return 'warm';
  return 'cool';
}

function buildSummary() {
  const lines = MARKET_DATA.map(
    (a) =>
      `${a.name} (${a.type}): plumbing ${a.demand.plumbing}, electrical ${a.demand.electrical}, renovation ${a.demand.renovation}, building ${a.demand.building}. Signal: ${a.signal}.`
  );
  return lines.join('\n');
}

function AiBriefing() {
  const [brief, setBrief] = useState(() => localStorage.getItem('ch-ai-brief'));
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');

  async function generate() {
    setBusy(true);
    setError('');
    try {
      const text = await analyseMarket(buildSummary());
      if (text) {
        setBrief(text);
        localStorage.setItem('ch-ai-brief', text);
      }
    } catch {
      setError('The analysis could not be generated right now. Try again shortly.');
    } finally {
      setBusy(false);
    }
  }

  return (
    <div className="ai-brief">
      <div className="ai-brief-head">
        <div>
          <h3>AI market briefing</h3>
          <p>
            {AI_ENABLED
              ? `Generated by ${AI_MODEL} from the demand matrix above.`
              : 'Add a free Groq API key to enable AI-generated briefings (see docs/AI.md).'}
          </p>
        </div>
        {AI_ENABLED && (
          <button className="btn" onClick={generate} disabled={busy}>
            <Icon name="spark" /> {busy ? 'Analysing…' : brief ? 'Regenerate' : 'Generate briefing'}
          </button>
        )}
      </div>
      {error && <p className="ai-error">{error}</p>}
      {brief ? (
        <div className="ai-brief-body">
          {brief.split(/\n{2,}|\n(?=\d\.)/).map((para, i) => (
            <p key={i}>{para}</p>
          ))}
        </div>
      ) : (
        !AI_ENABLED && (
          <div className="ai-brief-body ai-brief-static">
            <p>
              Strongest overall demand sits in the older, denser suburbs —
              Sunnyside, Arcadia and Hatfield — where ageing plumbing and
              rental churn drive steady reactive work. Renovation spend
              concentrates in the established southern suburbs (Waterkloof,
              Groenkloof, Brooklyn), while new building work tracks the
              growth corridors in Centurion and Montana.
            </p>
          </div>
        )
      )}
    </div>
  );
}

export default function Insights() {
  const [service, setService] = useState('plumbing');
  const ranked = useMemo(() => topAreas(service, MARKET_DATA.length), [service]);

  return (
    <>
      <section className="page-header">
        <div className="wrap">
          <div className="crumbs">
            <Link to="/">Home</Link>
            <Icon name="arrowRight" />
            <span>Market insights</span>
          </div>
          <h1>Where the work is.</h1>
          <p>
            A modelled view of demand for our trades across Pretoria suburbs —
            built to focus marketing and quoting effort where it pays back.
          </p>
        </div>
      </section>

      <section className="section">
        <div className="wrap">
          <FadeIn>
            <SectionHeading eyebrow="Demand model" title="Demand by suburb and trade">
              Scores are directional estimates from housing-stock age, dwelling
              type and development activity — not measured sales data.
            </SectionHeading>
          </FadeIn>

          <FadeIn delay={80}>
            <div className="filter-row" role="group" aria-label="Select trade">
              {SERVICES.map((s) => (
                <button
                  key={s.id}
                  className={`filter-btn ${service === s.id ? 'active' : ''}`}
                  aria-pressed={service === s.id}
                  onClick={() => setService(s.id)}
                >
                  {s.label}
                </button>
              ))}
            </div>
          </FadeIn>

          <div className="demand-table" role="table" aria-label="Demand ranking">
            {ranked.map((area, i) => {
              const score = area.demand[service];
              return (
                <FadeIn key={area.id} delay={Math.min(i, 8) * 40}>
                  <div className="demand-row" role="row">
                    <span className="demand-rank">{String(i + 1).padStart(2, '0')}</span>
                    <span className="demand-thumb">
                      <img src={areaImage[area.id]} alt="" loading="lazy" />
                    </span>
                    <span className="demand-area">
                      <strong>{area.name}</strong>
                      <small>{area.type}</small>
                    </span>
                    <span className="demand-signal">{area.signal}</span>
                    <span className="demand-score">
                      <span className={`demand-bar ${demandClass(score)}`}>
                        <i style={{ width: `${score}%` }} />
                      </span>
                      <b>{score}</b>
                    </span>
                  </div>
                </FadeIn>
              );
            })}
          </div>

          <FadeIn delay={100}>
            <VizBoard />
          </FadeIn>

          <FadeIn delay={110}>
            <AiBriefing />
          </FadeIn>

          <FadeIn delay={120}>
            <p className="portfolio-note">
              Methodology: modelled estimates from public signals (housing-stock
              age, dwelling type, rental density and development activity). Not
              measured sales or enquiry data — replace with real job records as
              they accumulate.
            </p>
          </FadeIn>
        </div>
      </section>
    </>
  );
}
